import { qmlPackOptions } from "@stef/effect-platform-qml/build";
import { Effect, FileSystem, Path, Schema } from "effect";
import { build as pack } from "vite-plus/pack";
import { type BuildMode, type PluginConfig, pluginIdFor } from "./define.ts";
import { PluginManifest } from "./manifest.ts";

export class PluginBuildError extends Schema.TaggedError<PluginBuildError>()(
  "@stef/plugin-kit/PluginBuildError",
  { message: Schema.String, cause: Schema.optionalKey(Schema.Defect()) },
) {}

const ID_LINE = /^local PLUGIN_ID = "[^"]*" -- plugin-kit:id$/m;

/** Points a Lua hook at the built plugin id; fails if the marked line is missing. */
export const rewriteHookPluginId = (source: string, id: string) =>
  ID_LINE.test(source)
    ? Effect.succeed(source.replace(ID_LINE, `local PLUGIN_ID = "${id}" -- plugin-kit:id`))
    : Effect.fail(
        new PluginBuildError({
          message: 'hypr hook has no `local PLUGIN_ID = "…" -- plugin-kit:id` line',
        }),
      );

/** `lib/meta.mjs`: what QML imports as `import "lib/meta.mjs" as Meta`. */
export const metaModule = (id: string, mode: BuildMode) =>
  [
    "// Generated by @stef/plugin-kit. Do not edit.",
    `export const pluginId = ${JSON.stringify(id)};`,
    `export const mode = ${JSON.stringify(mode)};`,
    "",
  ].join("\n");

export const manifestFor = (config: PluginConfig, mode: BuildMode) =>
  Schema.encodeEffect(PluginManifest)({
    schemaVersion: 1,
    id: pluginIdFor(config, mode),
    name: mode === "dev" ? `${config.name} (dev)` : config.name,
    version: config.version,
    ...(config.author === undefined ? {} : { author: config.author }),
    ...(config.description === undefined ? {} : { description: config.description }),
    kinds: config.kinds,
    entryPoints: config.entryPoints,
    ...(config.keepLoaded === undefined ? {} : { keepLoaded: config.keepLoaded }),
  }).pipe(
    Effect.mapError(
      (cause) => new PluginBuildError({ message: `invalid manifest: ${cause.message}`, cause }),
    ),
  );

/**
 * Builds a complete plugin folder at `<root>/dist/<mode>/<id>`: manifest, QML,
 * `lib/*.mjs` bundles for the QML engine, the generated `lib/meta.mjs`, and
 * the Hyprland hook. Returns the folder.
 */
export const buildPlugin = Effect.fn("PluginKit.build")(function* (
  root: string,
  config: PluginConfig,
  mode: BuildMode,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;

  const id = pluginIdFor(config, mode);
  const outDir = path.join(root, "dist", mode, id);
  const libDir = path.join(outDir, "lib");
  const manifest = yield* manifestFor(config, mode);

  yield* fs.remove(outDir, { recursive: true, force: true });
  yield* fs.makeDirectory(libDir, { recursive: true });

  const qmlDir = path.join(root, config.qml ?? "qml");
  for (const file of yield* fs.readDirectory(qmlDir)) {
    yield* fs.copyFile(path.join(qmlDir, file), path.join(outDir, file));
  }

  for (const file of config.files ?? []) {
    yield* fs.copyFile(path.join(root, file), path.join(outDir, path.basename(file)));
  }

  if (config.hyprHook !== undefined) {
    const hook = yield* fs.readFileString(path.join(root, config.hyprHook));
    yield* fs.writeFileString(path.join(outDir, "hypr.lua"), yield* rewriteHookPluginId(hook, id));
  }

  if (config.libs !== undefined && Object.keys(config.libs).length > 0) {
    const entry = config.libs;
    yield* Effect.tryPromise({
      try: () =>
        pack({
          ...qmlPackOptions(),
          config: false,
          cwd: root,
          entry: { ...entry },
          outDir: libDir,
          clean: false,
          logLevel: "warn",
        }),
      catch: (cause) => new PluginBuildError({ message: "bundling lib/*.mjs failed", cause }),
    });
  }

  yield* fs.writeFileString(path.join(libDir, "meta.mjs"), metaModule(id, mode));
  yield* fs.writeFileString(
    path.join(outDir, "manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );

  return outDir;
});
