import { defaultTokens, type Tokens } from "@stef/tokens/runtime";
import { Brand, Context, Effect, FileSystem, Path, PlatformError, Schema } from "effect";
import type { ThemePalette } from "../colors.ts";

export type ThemePath = string & Brand.Brand<"ThemePath">;
export const ThemePath = Brand.nominal<ThemePath>();
/** Directory the theme files are written to, e.g. `~/.config/omarchy/themes/<name>`. */
export const ThemeOutputDirectory = Context.Service<ThemePath>(
  "@stef/theme-engine/ThemeOutputDirectory",
);

/**
 * The design tokens theme files are rendered with (shape, spacing, density,
 * motion scheme, the flyout exception). Read when a file is written, so the
 * caller provides the tokens in effect at that moment (Studio: tokens.json).
 */
export const ThemeTokens = Context.Reference<Tokens>("@stef/theme-engine/ThemeTokens", {
  defaultValue: () => defaultTokens,
});

export type ThemeFileWriter = (
  palette: ThemePalette,
) => Effect.Effect<void, PlatformError.PlatformError>;

/** A writer for one theme file, rendered from the palette and the tokens in context. */
export const makeThemeFileWriter = (
  fileId: string,
  render: (palette: ThemePalette, tokens: Tokens) => string,
) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const outPath = path.join(yield* ThemeOutputDirectory, fileId);
    const write: ThemeFileWriter = (palette) =>
      Effect.gen(function* () {
        const tokens = yield* ThemeTokens;
        yield* fs.writeFileString(outPath, render(palette, tokens));
      });
    return write;
  });

export class OmarchyThemeError extends Schema.TaggedError<OmarchyThemeError>()(
  "@stef/theme-engine/OmarchyThemeError",
  { cause: Schema.Defect() },
) {}

export const generatedBy = "Generated by Omaterial (Material 3) for Omarchy v4.";
