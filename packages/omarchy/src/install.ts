import { Effect, FileSystem, Path, Schema } from "effect";
import { OmarchyPaths } from "./paths.ts";

/** Which build of each plugin is live: `prod` (`stef.x`) or `dev` (`stef.x.dev`). */
export const Variant = Schema.Literals(["prod", "dev"]);
export type Variant = typeof Variant.Type;

export const StefState = Schema.Struct({
  /** Base plugin id (`stef.periphery`) → the variant that is live. */
  active: Schema.Record(Schema.String, Variant),
});
export type StefState = typeof StefState.Type;

const emptyState: StefState = { active: {} };

export const variantId = (baseId: string, variant: Variant) =>
  variant === "dev" ? `${baseId}.dev` : baseId;

export const readState = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const paths = yield* OmarchyPaths;
  if (!(yield* fs.exists(paths.stateJson))) return emptyState;
  const text = yield* fs.readFileString(paths.stateJson);
  return yield* Schema.decodeUnknownEffect(Schema.fromJsonString(StefState))(text).pipe(
    Effect.orElseSucceed(() => emptyState),
  );
});

export const writeState = Effect.fn("Omarchy.writeState")(function* (state: StefState) {
  const fs = yield* FileSystem.FileSystem;
  const paths = yield* OmarchyPaths;
  yield* fs.makeDirectory(paths.stefDir, { recursive: true });
  yield* fs.writeFileString(paths.stateJson, `${JSON.stringify(state, null, 2)}\n`);
});

/**
 * Puts a built plugin folder in place as `~/.config/omarchy/plugins/<id>`.
 * The copy is staged under ~/.config/omarchy/stef (the shell reloads on any
 * write under plugins/, and would see a half-copied folder or a duplicate id),
 * then renamed in: the shell sees the old folder go and the new one arrive.
 */
export const installPlugin = Effect.fn("Omarchy.installPlugin")(function* (
  builtDir: string,
  id: string,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const paths = yield* OmarchyPaths;
  const stamp = Date.now().toString(36);
  const staging = path.join(paths.stefDir, "staging", `${id}-${stamp}`);
  const retired = path.join(paths.stefDir, "staging", `${id}-${stamp}.old`);
  const target = paths.pluginDir(id);

  yield* fs.makeDirectory(path.dirname(staging), { recursive: true });
  yield* fs.makeDirectory(paths.pluginsDir, { recursive: true });
  yield* fs.copy(builtDir, staging);
  if (yield* fs.exists(path.join(target, ".git"))) {
    return yield* Effect.fail(`${target} is a git repository; move it away before deploying`);
  }
  if (yield* fs.exists(target)) yield* fs.rename(target, retired);
  yield* fs.rename(staging, target);
  yield* fs.remove(retired, { recursive: true, force: true });
  return target;
});

export const uninstallPlugin = Effect.fn("Omarchy.uninstallPlugin")(function* (id: string) {
  const fs = yield* FileSystem.FileSystem;
  const paths = yield* OmarchyPaths;
  yield* fs.remove(paths.pluginDir(id), { recursive: true, force: true });
});

/**
 * `~/.config/hypr/stef/plugins.lua`: sources the Hyprland hook of the live
 * variant of each plugin, and only that one. Two variants' hooks would both
 * wrap the same dispatchers over the same globals.
 */
export const hooksLua = (hooks: ReadonlyArray<{ readonly id: string; readonly file: string }>) =>
  [
    "-- Generated by the stef CLI. Do not edit: `stef deploy` and `stef dev`",
    "-- rewrite it to load the live variant's hook of each plugin.",
    "",
    ...hooks.map(
      ({ id, file }) =>
        `-- ${id}\nlocal hook = ${JSON.stringify(file)}\nif io.open(hook) then dofile(hook) end\n`,
    ),
  ].join("\n");

export const writeHooksFile = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const paths = yield* OmarchyPaths;
  const state = yield* readState;
  const hooks: Array<{ id: string; file: string }> = [];
  for (const [baseId, variant] of Object.entries(state.active).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const id = variantId(baseId, variant);
    const file = path.join(paths.pluginDir(id), "hypr.lua");
    if (yield* fs.exists(file)) hooks.push({ id, file });
  }
  yield* fs.makeDirectory(paths.stefHyprDir, { recursive: true });
  const target = path.join(paths.stefHyprDir, "plugins.lua");
  yield* fs.writeFileString(target, hooksLua(hooks));
  return { file: target, hooks: hooks.length };
});

/** The block `hyprland.lua` has loaded periphery's hook with since before the monorepo. */
export const legacyPeripheryHookBlock = `local periphery_hook = os.getenv("HOME") .. "/.config/omarchy/plugins/stef.periphery/hypr.lua"
if io.open(periphery_hook) then dofile(periphery_hook) end`;

export const hooksIncludeBlock = `local stef_hooks = os.getenv("HOME") .. "/.config/hypr/stef/plugins.lua"
if io.open(stef_hooks) then dofile(stef_hooks) end`;

export type HooksInstallResult =
  | { readonly _tag: "AlreadyInstalled" }
  | { readonly _tag: "Installed"; readonly backup: string }
  | { readonly _tag: "Manual"; readonly reason: string };

/**
 * Points hyprland.lua at plugins.lua instead of periphery's hook. Only edits
 * when the exact legacy block is there; keeps a backup next to it.
 */
export const installHooksInclude = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const paths = yield* OmarchyPaths;
  const file = path.join(paths.hyprDir, "hyprland.lua");
  if (!(yield* fs.exists(file))) {
    return { _tag: "Manual", reason: `${file} does not exist` } as HooksInstallResult;
  }
  const text = yield* fs.readFileString(file);
  if (text.includes(hooksIncludeBlock)) return { _tag: "AlreadyInstalled" } as HooksInstallResult;
  if (!text.includes(legacyPeripheryHookBlock)) {
    return {
      _tag: "Manual",
      reason: `periphery's hook block isn't in ${file}; add this before Omarchy's bindings:\n${hooksIncludeBlock}`,
    } as HooksInstallResult;
  }
  const backup = `${file}.bak-${Date.now()}`;
  yield* fs.copyFile(file, backup);
  yield* fs.writeFileString(file, text.replace(legacyPeripheryHookBlock, hooksIncludeBlock));
  return { _tag: "Installed", backup } as HooksInstallResult;
});
